def make_advice(kind: str, sensors=()) -> dict:
    """依事件及相關感測器提供完整檢查建議。

    Args:
        kind: 事件類型。
        sensors: 受影響的感測器欄位名稱，不包含無效量測推測出的設備故障。

    Returns:
        候選原因、三個檢查步驟及由相同步驟組成的完整建議。
    """
    ordered = [sensor for sensor in SENSOR_NAMES if sensor in sensors]
    combination = "_".join(ordered)
    key = (combination if len(ordered) >= 2 and kind in
           ("multisensor", "joint", "thermal", "pressure", "vibration") else kind)
    title, causes, steps = PLAYBOOKS[key]
    sensor_name = "、".join(SENSOR_NAMES[sensor] for sensor in ordered) or "相關"
    actions = [step.format(sensor=sensor_name) for step in steps]
    return {
        "title": title.format(sensor=sensor_name),
        "causes": list(causes),
        "actions": actions,
        "recommendation": "".join(actions),
        "source": "本機規則模板",
    }
